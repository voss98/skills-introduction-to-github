export const FONT_CHARS = Object.keys(G).join('');

/** Rows of the glyph as booleans; unknown characters fall back to '?'. */
export function glyphRows(ch: string): boolean[][] {
  const src = G[ch] ?? G['?'];
  return src.split(' ').map((row) => [...row].map((c) => c === '#'));
}

/** Normalise any string to characters the font can draw. */
export function toFontText(text: string): string {
  return [...text.toUpperCase()]
    .map((c) => (c === '\n' ? c : G[c] !== undefined ? c : '?'))
    .join('');
}

/** Word-wrap text to a max number of characters per line. Respects explicit newlines. */
export function wrapText(text: string, maxChars: number): string[] {
  const out: string[] = [];
  for (const para of toFontText(text).split('\n')) {
    let line = '';
    for (const word of para.split(' ')) {
      if (word.length > maxChars) {
        if (line) out.push(line);
        for (let i = 0; i < word.length; i += maxChars) out.push(word.slice(i, i + maxChars));
        line = out.pop() ?? '';
        continue;
      }
      const candidate = line ? `${line} ${word}` : word;
      if (candidate.length > maxChars) {
        out.push(line);
        line = word;
      } else {
        line = candidate;
      }
    }
    out.push(line);
  }
  return out;
}
